    private void actualizarDir(){
        Lista direc = this.sim.getDirectorios();
        Nodo cabeza = direc.getPrimero();
        while(cabeza!=null){
            Directorio ac = (Directorio) cabeza.getDato();
            this.directorio.addItem(ac.getNombre());
            cabeza=cabeza.getSiguiente();
        }
    }

